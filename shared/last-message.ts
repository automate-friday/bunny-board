// The last message the person sent an agent ("You: …" in its thread, tiles and cards), from
// the agent's timeline rows (server/timeline.ts simplifyItem).
//
// A "user" row is not always the person: the board also writes to agents. Not counted:
// - the board's opening primer, unless the person typed an opening line (row.text);
// - the board introduction (INTRO_ROW);
// - board changes (kind "plugin:board-delta", not "user");
// - messages other agents or the board deliver as "user" turns, by their fixed openings
//   (AGENT_DELIVERED): af-network handoffs ("[Network handoff …]", from another machine's agent
//   or the board), board deltas sent as text, the organizer's (Bunny's) relays, frame
//   compression requests, stamp reactions, arrow-channel messages from other frames, and
//   Claude Code's own turns (Stop/tool hook feedback, background task notifications, command
//   echoes, "[Request interrupted by user…]");
// - agent echoes (kind "assistant").
// When the newest "user" rows are all of these, the person's previous message is still shown.
// Files sent with the reply box arrive as "File supplied as context (upload …)" rows: a run of
// them with no text is "📎 N images" (or files); with text, the text is what is shown.

import { INTRO_ROW, type TranscriptRow } from "./components/transcript";

export type LastSent = {
  // One line: the message, or "📎 2 images".
  text: string;
  at: string;
  images: number;
  files: number;
  // The row it came from (rows[index]), to scroll to; for an attachment run, its first row.
  index: number;
};

// Openings of "user" turns that no person typed (see above). Checked on the trimmed text.
export const AGENT_DELIVERED: readonly RegExp[] = [
  /^\[Network handoff [^\]]*\]/,
  /^Board delta [—-] /,
  /^Message from the board organizer\./,
  /^Compress this conversation into frame /,
  /^Stamp (?:approve|needs-change|question|do-next|stop|love-it|note:) /,
  /^Arrow channel \S+; message \S+; from frame /,
  /^(?:Stop|SubagentStop|PreToolUse|PostToolUse|UserPromptSubmit|SessionStart|Notification|PreCompact) hook (?:feedback|error|blocking error)\b/i,
  /^<(?:task-notification|system-reminder|command-name|command-message|local-command-stdout|local-command-stderr|bash-input|bash-stdout|bash-stderr)>/,
  /^Caveat: The messages below were generated by the user while running local commands/,
  /^\[Request interrupted by user/,
];

// Whether a "user" row's text was delivered by an agent, the board or the harness.
export function agentDelivered(text: string): boolean {
  const t = text.trimStart();
  return AGENT_DELIVERED.some((re) => re.test(t));
}
const UPLOAD = /^File supplied as context \(upload [^)]*\)\.\s*\nName: ("(?:[^"\\]|\\.)*")/;
const IMAGE_NAME = /\.(png|jpe?g|gif|webp|heic|heif|avif)$/i;

// What one row is, for this purpose.
function classify(r: TranscriptRow): { kind: "said"; text: string } | { kind: "file"; image: boolean } | null {
  if (r.kind !== "user" || r.ack) return null;
  if (r.primer) return r.text.trim() ? { kind: "said", text: r.text } : null;
  const text = r.text ?? "";
  if (!text.trim() || text === INTRO_ROW || agentDelivered(text)) return null;
  const up = UPLOAD.exec(text);
  if (up) {
    let name = "";
    try {
      name = JSON.parse(up[1]) as string;
    } catch {}
    return { kind: "file", image: IMAGE_NAME.test(name) };
  }
  return { kind: "said", text };
}

export function oneLine(text: string, max = 200): string {
  const t = text.replace(/\s+/g, " ").trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
}

export function attachmentLabel(images: number, files: number): string {
  const parts = [images ? `${images} image${images === 1 ? "" : "s"}` : "", files ? `${files} file${files === 1 ? "" : "s"}` : ""].filter(Boolean);
  return `📎 ${parts.join(", ")}`;
}

// The newest message the person sent, or null when they have sent nothing (in these rows).
export function lastHumanMessage(rows: readonly TranscriptRow[]): LastSent | null {
  let images = 0, files = 0, first = -1, at = "";
  for (let i = rows.length - 1; i >= 0; i--) {
    const c = classify(rows[i]);
    if (!c) {
      // Anything else (the agent answering) ends a run of attachments.
      if (first >= 0 && rows[i].kind !== "user") break;
      continue;
    }
    if (c.kind === "file") {
      if (c.image) images++;
      else files++;
      first = i;
      at ||= rows[i].at;
      continue;
    }
    // Text: what the person wrote. Files sent with it (uploaded just before, or just after
    // when the text came first) are counted with it.
    for (let j = i - 1; j >= 0; j--) {
      const b = classify(rows[j]);
      if (b?.kind !== "file") break;
      if (b.image) images++;
      else files++;
    }
    return { text: oneLine(c.text), at: first >= 0 ? at : rows[i].at, images, files, index: i };
  }
  return first >= 0 ? { text: attachmentLabel(images, files), at, images, files, index: first } : null;
}

// Every message the person sent, newest first (hold "You: …" on a phone to list them and jump
// to one). Same rules as lastHumanMessage; each attachment is its own "📎 1 image" entry.
export function humanMessages(rows: readonly TranscriptRow[]): Array<Pick<LastSent, "text" | "at" | "index">> {
  const out: Array<Pick<LastSent, "text" | "at" | "index">> = [];
  for (let i = rows.length - 1; i >= 0; i--) {
    const c = classify(rows[i]);
    if (!c) continue;
    out.push({ text: c.kind === "said" ? oneLine(c.text) : attachmentLabel(c.image ? 1 : 0, c.image ? 0 : 1), at: rows[i].at, index: i });
  }
  return out;
}
